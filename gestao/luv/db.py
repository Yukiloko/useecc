"""Acesso ao banco: SQLite no computador, Postgres (Supabase) online.

O resto do código escreve SQL com `?` e lê linhas por nome (`r["id"]`) ou
posição (`r[0]`). Para o Postgres, este módulo traduz os `?`, devolve o id dos
INSERTs e entrega linhas com a mesma cara das do SQLite.
"""

import re
import sqlite3
from decimal import Decimal
from pathlib import Path
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit

from flask import current_app, g

SCHEMA = Path(__file__).with_name("schema.sql")
TABELAS_SEM_ID = {"config", "ficha_tecnica"}


def eh_postgres(alvo):
    return str(alvo).startswith(("postgres://", "postgresql://"))


def connect(alvo):
    if eh_postgres(alvo):
        return ConexaoPG(alvo)
    conn = sqlite3.connect(alvo)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def schema_postgres(sql):
    sql = sql.replace("INTEGER PRIMARY KEY", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    sql = re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql)
    sql = sql.replace("DEFAULT CURRENT_TIMESTAMP", "DEFAULT (now()::text)")
    # No Supabase, tabelas do esquema public ficam visíveis pela API REST automática.
    # Com RLS ligado e sem políticas, a API não enxerga nada; a ferramenta conecta
    # como dona das tabelas e continua lendo normalmente.
    tabelas = re.findall(r"CREATE TABLE IF NOT EXISTS (\w+)", sql)
    return sql + "\n" + "\n".join(f"ALTER TABLE {t} ENABLE ROW LEVEL SECURITY;" for t in tabelas)


def init_schema(conn, commit=True):
    sql = SCHEMA.read_text(encoding="utf-8")
    if isinstance(conn, ConexaoPG):
        # vários processos sobem juntos no servidor: só um cria as tabelas por vez
        conn.execute("SELECT pg_advisory_xact_lock(724913)")
        conn.executescript(schema_postgres(sql))
    else:
        conn.executescript(sql)
    if commit:
        conn.commit()


def get_db():
    if "db" not in g:
        g.db = connect(current_app.config["DATABASE"])
    return g.db


def close_db(_exc=None):
    db = g.pop("db", None)
    if db is not None:
        db.close()


def get_config(conn, chave, padrao=None):
    row = conn.execute("SELECT valor FROM config WHERE chave = ?", (chave,)).fetchone()
    return row["valor"] if row else padrao


def set_config(conn, chave, valor):
    conn.execute(
        "INSERT INTO config (chave, valor) VALUES (?, ?) "
        "ON CONFLICT(chave) DO UPDATE SET valor = excluded.valor",
        (chave, str(valor)),
    )


# ---------------------------------------------------------------- Postgres

class Linha:
    """Linha que se comporta como sqlite3.Row: r["coluna"], r[0], desempacotar e dict(r)."""

    __slots__ = ("_nomes", "_valores")

    def __init__(self, nomes, valores):
        self._nomes = nomes
        self._valores = valores

    def __getitem__(self, chave):
        if isinstance(chave, (int, slice)):
            return self._valores[chave]
        try:
            return self._valores[self._nomes.index(chave)]
        except ValueError:
            raise KeyError(chave) from None

    def keys(self):
        return list(self._nomes)

    def __iter__(self):
        return iter(self._valores)

    def __len__(self):
        return len(self._valores)

    def __repr__(self):
        return f"Linha({dict(zip(self._nomes, self._valores))})"


def _normal(v):
    if isinstance(v, Decimal):
        return int(v) if v == v.to_integral_value() else float(v)
    return v


def _fabrica_linha(cursor):
    nomes = [c.name for c in cursor.description] if cursor.description else []
    return lambda valores: Linha(nomes, [_normal(v) for v in valores])


def limpar_url(url):
    """Tira parâmetros que o Supabase/Vercel põem na URL e o libpq não aceita (ex.: supa=…)."""
    partes = urlsplit(url)
    aceitos = {"sslmode", "connect_timeout", "application_name", "options", "sslrootcert"}
    query = [(k, v) for k, v in parse_qsl(partes.query) if k in aceitos]
    if not any(k == "sslmode" for k, _ in query) and partes.hostname not in ("localhost", "127.0.0.1"):
        query.append(("sslmode", "require"))
    return urlunsplit(partes._replace(query=urlencode(query)))


class CursorPG:
    def __init__(self, cur, lastrowid=None):
        self._cur = cur
        self.lastrowid = lastrowid

    def fetchone(self):
        return self._cur.fetchone() if self._cur.description else None

    def fetchall(self):
        return self._cur.fetchall() if self._cur.description else []

    def __iter__(self):
        return iter(self.fetchall())


class ConexaoPG:
    _INSERT = re.compile(r"^\s*INSERT\s+INTO\s+(\w+)", re.I)

    def __init__(self, url):
        import psycopg

        # prepare_threshold=None: o pooler do Supabase (modo transação) não aceita prepared statements
        self.raw = psycopg.connect(limpar_url(url), row_factory=_fabrica_linha, prepare_threshold=None)

    def execute(self, sql, params=()):
        m = self._INSERT.match(sql)
        devolve_id = bool(m) and m.group(1).lower() not in TABELAS_SEM_ID and "RETURNING" not in sql.upper()
        if devolve_id:
            sql += " RETURNING id"
        cur = self.raw.cursor()
        if params:
            cur.execute(sql.replace("%", "%%").replace("?", "%s"), tuple(params))
        else:
            cur.execute(sql)
        lastrowid = cur.fetchone()[0] if devolve_id else None
        return CursorPG(cur, lastrowid)

    def executescript(self, sql):
        self.raw.execute(sql)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()
